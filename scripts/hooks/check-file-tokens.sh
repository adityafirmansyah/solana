#!/usr/bin/env bash
# ==============================================================================
# Git Pre-Commit Hook: File Token Limit Quality Gate
# Enforces: Maximum 5,000 tokens per file (Tokens = bytes / 4 -> Max 20,000 bytes)
# Scope: Staged files only (Added, Copied, Modified, Renamed)
# Exemptions: Lockfiles, binary assets, build outputs, codegen, and .tokenignore
# ==============================================================================

set -eo pipefail

MAX_TOKENS=5000
BYTES_PER_TOKEN=4
MAX_BYTES=$((MAX_TOKENS * BYTES_PER_TOKEN)) # 20,000 bytes

REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"

# Track if any violations are found
VIOLATIONS=0
VIOLATION_FILES=()

# Helper: check if file matches .tokenignore if present
is_tokenignored() {
    local target="$1"
    local ignore_file="$REPO_ROOT/.tokenignore"
    if [ ! -f "$ignore_file" ]; then
        return 1
    fi

    while IFS= read -r pattern || [ -n "$pattern" ]; do
        # Strip carriage return and leading/trailing whitespace
        pattern="$(echo "$pattern" | tr -d '\r' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
        [ -z "$pattern" ] && continue
        [[ "$pattern" =~ ^# ]] && continue

        # Direct match or path match
        # shellcheck disable=SC2053
        if [[ "$target" == $pattern ]] || [[ "$target" == */$pattern ]] || [[ "$target" == $pattern/* ]]; then
            return 0
        fi
    done < "$ignore_file"

    return 1
}

# Helper: check if file is exempt by path, extension, or name pattern
is_exempt_file() {
    local file="$1"
    local lower_file
    lower_file="$(echo "$file" | tr '[:upper:]' '[:lower:]')"

    # 1. Lockfiles & Tooling Wrappers
    case "$lower_file" in
        *package-lock.json|*npm-shrinkwrap.json|*yarn.lock|*pnpm-lock.yaml|*bun.lockb) return 0 ;;
        *cargo.lock|*composer.lock|*gemfile.lock|*go.sum|*pubspec.lock|*podfile.lock) return 0 ;;
        *poetry.lock|*pipfile.lock|*uv.lock|*requirements*.txt.lock) return 0 ;;
        *gradle-wrapper.jar|*gradlew|*gradlew.bat) return 0 ;;
    esac

    # 2. Binary Assets, Fonts, Media, Archives, and DB files
    case "$lower_file" in
        *.png|*.jpg|*.jpeg|*.gif|*.svg|*.webp|*.ico|*.avif) return 0 ;;
        *.woff|*.woff2|*.ttf|*.otf|*.eot) return 0 ;;
        *.mp3|*.wav|*.ogg|*.mp4|*.webm|*.avi|*.mov) return 0 ;;
        *.zip|*.tar|*.gz|*.bz2|*.xz|*.7z|*.rar|*.jar|*.aar|*.apk|*.aab|*.dex|*.class|*.so|*.dylib|*.bin|*.exe) return 0 ;;
        *.jks|*.keystore|*.p12|*.pem|*.crt|*.key) return 0 ;;
        *.db|*.db-shm|*.db-wal|*.db.bak|*.sqlite|*.sqlite3|*.parquet|*.npy|*.npz|*.pkl|*.pickle) return 0 ;;
    esac

    # 3. Minified assets, bundles, maps
    case "$lower_file" in
        *.min.js|*.min.css|*.map|*.bundle.js|*.bundle.css) return 0 ;;
    esac

    # 4. Build outputs & codegen directories / files
    case "$file" in
        build/*|*/build/*|.gradle/*|*/.gradle/*|dist/*|*/dist/*|out/*|*/out/*|.next/*|*/.next/*) return 0 ;;
        node_modules/*|*/node_modules/*|vendor/*|*/vendor/*) return 0 ;;
        generated/*|*/generated/*|schemas/*|*/schemas/*) return 0 ;;
        *BuildConfig.java|*R.java|*.pb.go|*_pb2.py|*.pb.cc) return 0 ;;
    esac

    # 5. Check .tokenignore
    if is_tokenignored "$file"; then
        return 0
    fi

    # 6. In-File Header Codegen Annotations (inspect first 40 lines)
    local header
    header="$(git show ":$file" 2>/dev/null | head -n 40 || true)"
    if echo "$header" | grep -Eq '(@generated|DO NOT EDIT|AUTO-GENERATED|Code generated by|[Gg]enerated by)'; then
        return 0
    fi

    return 1
}

# Collect staged files (Added, Copied, Modified, Renamed)
# Use -z to safely handle spaces and special characters
while IFS= read -r -d '' file; do
    [ -z "$file" ] && continue

    # Ensure object in index is a blob (skip submodules, gitlinks)
    obj_type="$(git cat-file -t ":$file" 2>/dev/null || true)"
    if [ "$obj_type" != "blob" ]; then
        continue
    fi

    # Check exemptions
    if is_exempt_file "$file"; then
        continue
    fi

    # Measure staged byte size directly from git index object
    staged_bytes="$(git cat-file -s ":$file" 2>/dev/null || echo 0)"

    if [ "$staged_bytes" -gt "$MAX_BYTES" ]; then
        staged_tokens=$(( staged_bytes / BYTES_PER_TOKEN ))
        excess_tokens=$(( staged_tokens - MAX_TOKENS ))
        excess_bytes=$(( staged_bytes - MAX_BYTES ))

        VIOLATIONS=$(( VIOLATIONS + 1 ))
        VIOLATION_FILES+=("$file|$staged_bytes|$staged_tokens|$excess_bytes|$excess_tokens")
    fi
done < <(git diff --cached --name-only --diff-filter=ACMR -z)

if [ "$VIOLATIONS" -gt 0 ]; then
    cat << "EOF"
================================================================================
[PRE-COMMIT ERROR] FILE TOKEN LIMIT EXCEEDED (Max: 5,000 tokens / 20,000 bytes)
================================================================================
Commit rejected! One or more staged agent-authored files exceed the repository
hygiene limit of 5,000 tokens (Tokens = bytes / 4; Maximum: 20,000 bytes).

Large monolithic files degrade agent context windows, impair reasoning quality,
and introduce high-risk merge collisions.

VIOLATING STAGED FILES:
EOF

    for item in "${VIOLATION_FILES[@]}"; do
        IFS='|' read -r v_file v_bytes v_tokens v_ex_bytes v_ex_tokens <<< "$item"
        printf "  - %s\n" "$v_file"
        printf "      Size:   %d bytes (~%d tokens)\n" "$v_bytes" "$v_tokens"
        printf "      Limit:  %d bytes (%d tokens)\n" "$MAX_BYTES" "$MAX_TOKENS"
        printf "      Excess: +%d bytes (+%d tokens over limit)\n\n" "$v_ex_bytes" "$v_ex_tokens"
    done

    cat << "EOF"
--------------------------------------------------------------------------------
EXPLICIT DECOMPOSITION & FILE SPLITTING INSTRUCTIONS:
--------------------------------------------------------------------------------
Please split large files into focused, single-responsibility modules under
5,000 tokens (< 20,000 bytes):

1. FRONTEND / UI MODULES:
   - Extract sub-views, cards, toolbars, and modals into discrete component files
     (e.g., `components/MyViewHeader.tsx`, `components/MyViewTable.tsx`).
   - Move custom state, queries, and business logic into dedicated hooks
     (e.g., `hooks/useMyViewData.ts`).
   - Separate design tokens, interfaces, and style constants into `types.ts` or `constants.ts`.

2. BACKEND / APIS & SCRIPTS:
   - Separate route definitions/controllers from domain business logic.
   - Extract service logic into domain services or helper classes
     (e.g., `services/order_service.py` vs `routers/orders.py`).
   - Relocate database queries and raw SQL into repository modules.
   - Move validation schemas and DTOs into dedicated schema files (e.g., `schemas/order.py`).

3. SERVICES, WORKERS & RUNTIMES:
   - Split multi-purpose execution scripts into discrete single-purpose tasks:
     * Listener / WebSocket / Polling engine
     * Signal calculation & state reducer
     * Order placement / execution gateway
   - Extract reusable utility functions into shared packages or helper modules.

4. CALL SITES & EXPORT SAFETY:
   - Retain public exports and top-level entrypoints via `__init__.py` or `index.ts`
     re-exports so existing call sites across the codebase do not break.
   - Grep for import paths before refactoring to prevent regressions.

RECOVERY GIT COMMANDS:
--------------------------------------------------------------------------------
To unstage and decompose:
  git restore --staged <violating-file>
  # Split the file into smaller modules under 5,000 tokens each
  git add <new-modular-files>
  git commit -m "<your-commit-message>"

(If a file is genuinely auto-generated or machine-managed, add '// @generated'
 or '# @generated' in the top 40 lines, or list it in .tokenignore)
================================================================================
EOF
    exit 1
fi

exit 0
